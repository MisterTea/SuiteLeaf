/**
 * Generated Office fixtures for the compatibility run. Each one is written by
 * an independent generator (docx, SheetJS, PptxGenJS), never by SuiteLeaf's
 * own exporters, so a SuiteLeaf export bug cannot also hide in the source.
 * The fixtures are generated in this repository and carry its license. They
 * contain no third-party documents.
 */
import { createHash } from "node:crypto";
import { crc32, deflateSync } from "node:zlib";
import type { CompatFormat, Probe } from "./types";

export interface FixtureSpec {
  id: string;
  format: CompatFormat;
  /** What the fixture is meant to exercise. */
  features: string[];
  /** What must still be there after each stage. */
  probes: Probe[];
  /** `supported` fixtures block a release when a probe is lost without a tolerated entry. */
  classification: "supported" | "rejected";
  generator: string;
}

export interface Fixture extends FixtureSpec {
  bytes: Uint8Array;
  /** Hash of the spec and generator versions. Generated bytes carry timestamps, so they are hashed per run instead. */
  specHash: string;
  sha256: string;
}

/** A 2×2 PNG with four distinct colors, so a recompressed or replaced picture changes its hash. */
export const FIXTURE_PNG = encodePng(2, 2, [255, 0, 0, 0, 255, 0, 0, 0, 255, 255, 255, 0]);

function encodePng(width: number, height: number, rgb: number[]): Uint8Array {
  const chunk = (type: string, data: Uint8Array) => {
    const head = Buffer.from(type, "ascii");
    const length = Buffer.alloc(4);
    length.writeUInt32BE(data.length);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(Buffer.concat([head, data])));
    return Buffer.concat([length, head, data, crc]);
  };
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0);
  header.writeUInt32BE(height, 4);
  header.set([8, 2, 0, 0, 0], 8);
  const rows: number[] = [];
  for (let y = 0; y < height; y += 1) rows.push(0, ...rgb.slice(y * width * 3, (y + 1) * width * 3));
  return new Uint8Array(
    Buffer.concat([
      Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
      chunk("IHDR", header),
      chunk("IDAT", deflateSync(Buffer.from(rows))),
      chunk("IEND", new Uint8Array()),
    ]),
  );
}

