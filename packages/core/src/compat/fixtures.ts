async function xlsxBudget(): Promise<Uint8Array> {
  const X = await import("xlsx");
  const costs = X.utils.aoa_to_sheet([
    ["Plot fees", "Cost"],
    ["North", 10],
    ["South", 20],
    ["East", 30],
    ["Total", { t: "n", f: "SUM(B2:B4)", v: 60 }],
  ]);
  const first = costs.A2 as { c?: { a: string; t: string }[] };
  first.c = [{ a: "Maya", t: "Check the totals" }];
  const summary = X.utils.aoa_to_sheet([["Doubled", { t: "n", f: "Costs!B5*2", v: 120 }]]);
  const book = X.utils.book_new();
  X.utils.book_append_sheet(book, costs, "Costs");
  X.utils.book_append_sheet(book, summary, "Summary");
  return new Uint8Array(X.write(book, { type: "array", bookType: "xlsx" }) as ArrayBuffer);
}

