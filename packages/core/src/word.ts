type Mark = NonNullable<JsonNode["marks"]>[number];
const normalize = (s: string) => s.replace(/[\s\u200b\ufeff]+/gu, "");
export function documentText(n: JsonNode): string {
  return textOf(n, n.type === "doc" ? citationLibrary(n) : undefined);
}
function textOf(n: JsonNode, library: CitationLibrary | undefined): string {
  const next = n.type === "doc" ? citationLibrary(n) : library;
  if (n.type === "equation") return String(n.attrs?.plain ?? "");
  if (n.type === "noteReference") return String(n.attrs?.label ?? "");
  if (n.type === "tableOfContents" || n.type === "bibliography") return "";
  if (n.type === "citation") {
    const source = next?.sources.find(
      (item) => item.id === String(n.attrs?.sourceId ?? ""),
    );
    return source && next ? inText(source, next.style) : "";
  }
  return (
    (n.text ?? "") +
    (n.content ?? []).map((child) => textOf(child, next)).join("")
  );
}
/** `droppedLinks` collects the addresses of links removed as unsafe. */
export function htmlToDocument(
  html: string,
  droppedLinks: string[] = [],
): JsonNode {
  const root = parseDocument(html, { decodeEntities: true });
  function inline(nodes: AnyNode[], marks: Mark[] = []): JsonNode[] {
    const out: JsonNode[] = [];
    for (const n of nodes) {
      if (n.type === "text") {
        if (n.data)
          out.push({
            type: "text",
            text: n.data,
            ...(marks.length ? { marks } : {}),
          });
        continue;
      }
      if (n.type !== "tag") continue;
      const e = n as Element,
        tag = e.name.toLowerCase();
      if (
        [
          "script",
          "style",
          "iframe",
          "object",
          "embed",
          "audio",
          "video",
        ].includes(tag)
      )
        continue;
      if (tag === "br") {
        out.push({ type: "hardBreak" });
        continue;
      }
      if (tag === "img") {
        if (
          /^data:image\/(png|jpeg|gif|webp);base64,/i.test(e.attribs.src ?? "")
        )
          out.push({
            type: "image",
            attrs: { src: e.attribs.src, alt: e.attribs.alt ?? "" },
          });
        else if (e.attribs.alt)
          out.push({ type: "text", text: `[${e.attribs.alt}]` });
        continue;
      }
      if (tag === "input" && e.attribs.type === "checkbox") {
        const checked =
          e.attribs.checked === "checked" ||
          e.attribs.checked === "" ||
          e.attribs.checked === "true";
        out.push({
          type: "text",
          text: checked ? "☒" : "☐",
          ...(marks.length ? { marks } : {}),
        });
        continue;
      }
      // Footnote marker labels are generated by Mammoth and aren't source text.
      const markType = (
        {
          strong: "bold",
          b: "bold",
          em: "italic",
          i: "italic",
          u: "underline",
          s: "strike",
          del: "strike",
          sup: "superscript",
          sub: "subscript",
          code: "code",
        } as Record<string, string>
      )[tag];
      const next = [...marks];
      if (markType && !next.some((m) => m.type === markType))
        next.push({ type: markType });
      // Symbol-font text, in its SuiteLeaf face (symbolSpans).
      if (tag === "span" && e.attribs["data-font"])
        next.push({ type: "textStyle", attrs: { fontFamily: e.attribs["data-font"] } });
      const href = tag === "a" ? (e.attribs.href ?? "") : "";
      if (href && safeLink(href))
        next.push({
          type: "link",
          attrs: { href, target: null },
        });
      else if (href) droppedLinks.push(href);
      out.push(...inline(e.children, next));
    }
    return out;
  }
  function attrs(e: Element) {
    const a: Record<string, unknown> = {};
    if (e.attribs.id) a.id = e.attribs.id.slice(0, 250);
    if (["rtl", "ltr"].includes(e.attribs.dir)) a.dir = e.attribs.dir;
    const style = e.attribs.style || "";
    const isCenter =
      e.attribs.class?.split(" ").includes("center") ||
      /text-align:\s*center/i.test(style) ||
      e.attribs.align === "center";
    if (isCenter) a.textAlign = "center";
    const isRight =
      e.attribs.class?.split(" ").includes("right") ||
      /text-align:\s*right/i.test(style) ||
      e.attribs.align === "right";
    if (isRight) a.textAlign = "right";
    const isJustify =
      e.attribs.class?.split(" ").includes("justify") ||
      /text-align:\s*justify/i.test(style) ||
      e.attribs.align === "justify";
    if (isJustify) a.textAlign = "justify";
    return a;
  }
  function paragraph(
    content: JsonNode[],
    attributes: Record<string, unknown> = {},
  ): JsonNode[] {
    const result: JsonNode[] = [];
    let current: JsonNode[] = [];
    for (const n of content) {
      if (n.type === "image") {
        if (current.length)
          result.push({
            type: "paragraph",
            attrs: attributes,
            content: current,
          });
        current = [];
        result.push(n);
      } else current.push(n);
    }
    if (current.length || !result.length)
      result.push({ type: "paragraph", attrs: attributes, content: current });
    return result;
  }
  const BLOCK_TAGS = new Set([
    "p",
    "h1",
    "h2",
    "h3",
    "h4",
    "h5",
    "h6",
    "ul",
    "ol",
    "li",
    "table",
    "tbody",
    "thead",
    "tfoot",
    "tr",
    "td",
    "th",
    "blockquote",
    "pre",
    "hr",
  ]);
  const hasBlockElement = (children: AnyNode[]): boolean =>
    children.some((child) => {
      if (child.type !== "tag") return false;
      const el = child as Element;
      const name = el.name.toLowerCase();
      return (
        BLOCK_TAGS.has(name) ||
        (el.children ? hasBlockElement(el.children) : false)
      );
    });
  const containerBlocks = (children: AnyNode[]): JsonNode[] => {
    if (!hasBlockElement(children)) {
      const inlines = inline(children);
      return inlines.length ? paragraph(inlines) : [{ type: "paragraph" }];
    }
    const b = blocks(children);
    return b.length ? b : [{ type: "paragraph" }];
  };
  function blocks(nodes: AnyNode[]): JsonNode[] {
    const out: JsonNode[] = [];
    for (const n of nodes) {
      if (n.type === "text") {
        if (n.data.trim()) out.push(...paragraph(inline([n])));
        continue;
      }
      if (n.type !== "tag") continue;
      const e = n as Element,
        t = e.name.toLowerCase();
      if (["script", "style", "iframe", "object", "embed"].includes(t))
        continue;
      if (t === "p") {
        out.push(...paragraph(inline(e.children), attrs(e)));
      } else if (/^h[1-6]$/.test(t)) {
        const pieces = inline(e.children);
        const text = pieces.filter((n) => n.type !== "image");
        if (text.length)
          out.push({
            type: "heading",
            attrs: { ...attrs(e), level: +t[1] },
            content: text,
          });
        for (const image of pieces) if (image.type === "image") out.push(image);
      } else if (t === "ul" || t === "ol") {
        const children = e.children.filter(
          (n) => n.type === "tag" && (n as Element).name === "li",
        ) as Element[];
        out.push({
          type: t === "ol" ? "orderedList" : "bulletList",
          attrs: t === "ol" ? { start: Number(e.attribs.start) || 1 } : {},
          content: children.map((li) => {
            const b = containerBlocks(li.children);
            return {
              type: "listItem",
              content:
                b[0].type === "paragraph" ? b : [{ type: "paragraph" }, ...b],
            };
          }),
        });
      } else if (t === "table") {
        const rows: Element[] = [];
        function findRows(es: AnyNode[]) {
          for (const c of es) {
            if (c.type !== "tag") continue;
            const child = c as Element;
            if (child.name === "tr") rows.push(child);
            else if (["tbody", "thead", "tfoot"].includes(child.name))
              findRows(child.children);
          }
        }
        findRows(e.children);
        const content = rows
          .map((row) => ({
            type: "tableRow",
            content: row.children
              .filter(
                (c) =>
                  c.type === "tag" &&
                  ["td", "th"].includes((c as Element).name),
              )
              .map((c) => {
                const cell = c as Element;
                const body = containerBlocks(cell.children);
                return {
                  type: cell.name === "th" ? "tableHeader" : "tableCell",
                  attrs: {
                    colspan: Math.max(
                      1,
                      Math.min(1000, Number(cell.attribs.colspan) || 1),
                    ),
                    rowspan: Math.max(
                      1,
                      Math.min(1000, Number(cell.attribs.rowspan) || 1),
                    ),
                    colwidth: null,
                  },
                  content: body.length ? body : [{ type: "paragraph" }],
                };
              }),
          }))
          .filter((row) => row.content.length);
        if (content.length) out.push({ type: "table", content });
      } else if (t === "blockquote")
        out.push({ type: "blockquote", content: blocks(e.children) });
      else if (t === "pre")
        out.push({
          type: "codeBlock",
          content: inline(e.children).map((n) => ({ ...n, marks: [] })),
        });
      else if (t === "hr") out.push({ type: "horizontalRule" });
      else if (t === "img") out.push(...paragraph(inline([e])));
      else if (
        [
          "a",
          "b",
          "code",
          "del",
          "em",
          "i",
          "s",
          "span",
          "strong",
          "sub",
          "sup",
          "u",
        ].includes(t) &&
        !hasBlockElement(e.children)
      ) {
        const inlines = inline([e]);
        if (inlines.some((n) => n.type !== "text" || n.text?.trim()))
          out.push(...paragraph(inlines));
      } else out.push(...blocks(e.children));
    }
    return out;
  }
  const content = blocks(root.children);
  return {
    type: "doc",
    content: content.length ? content : [{ type: "paragraph" }],
  };
}

function toLowerRoman(n: number): string {
  const romans: [number, string][] = [
    [1000, "m"],
    [900, "cm"],
    [500, "d"],
    [400, "cd"],
    [100, "c"],
    [90, "xc"],
    [50, "l"],
    [40, "xl"],
    [10, "x"],
    [9, "ix"],
    [5, "v"],
    [4, "iv"],
    [1, "i"],
  ];
  let res = "";
  for (const [val, sym] of romans) {
    while (n >= val) {
      res += sym;
      n -= val;
    }
  }
  return res || String(n);
}

