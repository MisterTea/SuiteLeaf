function parseWordStyles(stylesXml: string): Map<string, StyleInfo> {
  const styles = new Map<string, StyleInfo>();
  if (!stylesXml) return styles;

  const styleRegex = /<w:style\b([^>]*)>([\s\S]*?)<\/w:style>/g;
  let match: RegExpExecArray | null;
  while ((match = styleRegex.exec(stylesXml)) !== null) {
    const attrs = match[1];
    const body = match[2];
    const idMatch = attrs.match(/w:styleId="([^"]+)"/);
    const typeMatch = attrs.match(/w:type="([^"]+)"/);
    if (!idMatch) continue;
    const id = idMatch[1];
    const type = typeMatch ? typeMatch[1] : "";

    const nameMatch = body.match(/<w:name\b[^>]*w:val="([^"]+)"/);
    const basedOnMatch = body.match(/<w:basedOn\b[^>]*w:val="([^"]+)"/);
    const outlineMatch = body.match(/<w:outlineLvl\b[^>]*w:val="([^"]+)"/);

    let numPr: { numId: string; ilvl: string } | undefined;
    const numPrMatch = body.match(/<w:numPr>([\s\S]*?)<\/w:numPr>/);
    if (numPrMatch) {
      const numIdMatch = numPrMatch[1].match(/<w:numId\b[^>]*w:val="([^"]+)"/);
      const ilvlMatch = numPrMatch[1].match(/<w:ilvl\b[^>]*w:val="([^"]+)"/);
      if (numIdMatch && ilvlMatch) {
        numPr = { numId: numIdMatch[1], ilvl: ilvlMatch[1] };
      }
    }

    const hasBold =
      /<w:rPr>[\s\S]*?<w:b(?:\s+[^>]*w:val="(?:true|1|on)")?(?:\/|\s*>[\s\S]*?<\/w:b)[\s\S]*?<\/w:rPr>/.test(
        body,
      ) || /<w:rPr>[\s\S]*?<w:b\/>[\s\S]*?<\/w:rPr>/.test(body);
    const boldDisabled =
      /<w:rPr>[\s\S]*?<w:b\s+[^>]*w:val="(?:false|0|off)"/.test(body);
    const isBold = hasBold && !boldDisabled;

    let tableFirstRowBold = false;
    let tableFirstColBold = false;
    if (type === "table") {
      const firstRowMatch = body.match(
        /<w:tblStylePr\b[^>]*w:type="firstRow"[\s\S]*?<\/w:tblStylePr>/,
      );
      if (
        firstRowMatch &&
        /<w:b(?:\/|\s|>)/.test(firstRowMatch[0]) &&
        !/w:val="(?:false|0|off)"/.test(firstRowMatch[0])
      ) {
        tableFirstRowBold = true;
      }
      const firstColMatch = body.match(
        /<w:tblStylePr\b[^>]*w:type="firstCol"[\s\S]*?<\/w:tblStylePr>/,
      );
      if (
        firstColMatch &&
        /<w:b(?:\/|\s|>)/.test(firstColMatch[0]) &&
        !/w:val="(?:false|0|off)"/.test(firstColMatch[0])
      ) {
        tableFirstColBold = true;
      }
    }

    styles.set(id, {
      id,
      type,
      name: nameMatch ? nameMatch[1] : undefined,
      basedOn: basedOnMatch ? basedOnMatch[1] : undefined,
      outlineLvl: outlineMatch ? parseInt(outlineMatch[1], 10) : undefined,
      numPr,
      isBold,
      tableFirstRowBold,
      tableFirstColBold,
    });
  }

  // Resolve inheritance
  for (const style of styles.values()) {
    let curr = style;
    const visited = new Set<string>([style.id]);
    while (curr.basedOn && styles.has(curr.basedOn)) {
      if (visited.has(curr.basedOn)) break;
      visited.add(curr.basedOn);
      const parent = styles.get(curr.basedOn)!;
      if (style.outlineLvl === undefined && parent.outlineLvl !== undefined) {
        style.outlineLvl = parent.outlineLvl;
      }
      if (!style.isBold && parent.isBold) {
        style.isBold = true;
      }
      if (!style.numPr && parent.numPr) {
        style.numPr = parent.numPr;
      }
      curr = parent;
    }

    if (
      style.outlineLvl !== undefined &&
      style.outlineLvl >= 0 &&
      style.outlineLvl <= 8
    ) {
      style.isHeading = true;
      style.headingLevel = Math.min(6, style.outlineLvl + 1);
    } else {
      const name = style.name || style.id;
      const m = name.match(
        /(?:heading|titre|überschrift|encabezado)\s*([1-6])/i,
      );
      if (m) {
        style.isHeading = true;
        style.headingLevel = parseInt(m[1], 10);
      } else if (name.toLowerCase() === "title") {
        style.isHeading = true;
        style.headingLevel = 1;
      } else if (name.toLowerCase() === "subtitle") {
        style.isHeading = true;
        style.headingLevel = 2;
      }
    }
  }

  return styles;
}

function parseWordNumbering(numXml: string) {
  const nums = new Map<string, string>();
  const abstractNums = new Map<string, Map<number, NumberingLevel>>();
  const pStyleToNum = new Map<string, { numId: string; ilvl: number }>();
  if (!numXml) return { nums, abstractNums, pStyleToNum };

  const absRegex =
    /<w:abstractNum\b[^>]*w:abstractNumId="([^"]+)"[\s\S]*?<\/w:abstractNum>/g;
  let absMatch: RegExpExecArray | null;
  while ((absMatch = absRegex.exec(numXml)) !== null) {
    const absId = absMatch[1];
    const absBody = absMatch[0];
    const levels = new Map<number, NumberingLevel>();

    const lvlRegex = /<w:lvl\b[^>]*w:ilvl="([^"]+)"[\s\S]*?<\/w:lvl>/g;
    let lvlMatch: RegExpExecArray | null;
    while ((lvlMatch = lvlRegex.exec(absBody)) !== null) {
      const ilvl = parseInt(lvlMatch[1], 10);
      const lvlBody = lvlMatch[0];

      const startMatch = lvlBody.match(/<w:start\b[^>]*w:val="([^"]+)"/);
      const fmtMatch = lvlBody.match(/<w:numFmt\b[^>]*w:val="([^"]+)"/);
      const txtMatch = lvlBody.match(/<w:lvlText\b[^>]*w:val="([^"]+)"/);
      const pStyleMatch = lvlBody.match(/<w:pStyle\b[^>]*w:val="([^"]+)"/);

      levels.set(ilvl, {
        start: startMatch ? parseInt(startMatch[1], 10) : 1,
        numFmt: fmtMatch ? fmtMatch[1] : "decimal",
        lvlText: txtMatch ? txtMatch[1] : `%${ilvl + 1}`,
        pStyle: pStyleMatch ? pStyleMatch[1] : undefined,
      });
    }
    abstractNums.set(absId, levels);
  }

  const numRegex = /<w:num\b[^>]*w:numId="([^"]+)"[\s\S]*?<\/w:num>/g;
  let numMatch: RegExpExecArray | null;
  while ((numMatch = numRegex.exec(numXml)) !== null) {
    const numId = numMatch[1];
    const numBody = numMatch[0];
    const absRefMatch = numBody.match(/<w:abstractNumId\b[^>]*w:val="([^"]+)"/);
    if (absRefMatch) {
      const absId = absRefMatch[1];
      nums.set(numId, absId);

      const levels = abstractNums.get(absId);
      if (levels) {
        for (const [ilvl, lvl] of levels.entries()) {
          if (lvl.pStyle) {
            pStyleToNum.set(lvl.pStyle, { numId, ilvl });
          }
        }
      }
    }
  }

  return { nums, abstractNums, pStyleToNum };
}

/** Every visible run is directly bold, so a flattened cover-page line can keep that bold. */
function coverTextIsBold(xml: string): boolean {
  const runs = [...xml.matchAll(/<w:r\b[^>]*>[\s\S]*?<\/w:r>/g)].map((match) => match[0]);
  const textRuns = runs.filter((run) => /<w:t\b[^>]*>\s*\S/.test(run));
  return (
    textRuns.length > 0 &&
    textRuns.every(
      (run) => /<w:b\b/.test(run) && !/<w:b\b[^>]*w:val="(?:0|false|off)"/.test(run),
    )
  );
}

function makeBoldRuns(xml: string): string {
  return xml.replace(
    /<w:r\b([^>]*)>([\s\S]*?)<\/w:r>/g,
    (all, rAttrs, rBody) => {
      if (/<w:rPr>/.test(rBody)) {
        if (/<w:b(?:\/|\s|>)/.test(rBody)) return all;
        return (
          `<w:r${rAttrs}>` +
          rBody.replace(/<w:rPr>/, "<w:rPr><w:b/>") +
          `</w:r>`
        );
      }
      return `<w:r${rAttrs}><w:rPr><w:b/></w:rPr>${rBody}</w:r>`;
    },
  );
}

function formatNumber(val: number, fmt: string): string {
  if (fmt === "lowerLetter") {
    return String.fromCharCode(97 + ((val - 1) % 26));
  }
  if (fmt === "upperLetter") {
    return String.fromCharCode(65 + ((val - 1) % 26));
  }
  return String(val);
}

/** A match must include a nested table or text box, not stop at the first closing tag inside it. */
function balancedWordRanges(
  xml: string,
  tag: "w:p" | "w:tr" | "w:tbl",
): Array<[number, number]> {
  const out: Array<[number, number]> = [];
  const token = new RegExp(`<(/?)${tag}(?:\\s[^>]*?)?(/?)>`, "g");
  let match: RegExpExecArray | null;
  let depth = 0;
  let start = -1;
  while ((match = token.exec(xml))) {
    if (match[2] === "/") continue;
    if (!match[1]) {
      if (depth === 0) start = match.index;
      depth += 1;
    } else if (depth > 0) {
      depth -= 1;
      if (depth === 0 && start >= 0) {
        out.push([start, match.index + match[0].length]);
        start = -1;
      }
    }
  }
  return out;
}

function balancedWordElements(xml: string, tag: "w:p" | "w:tr" | "w:tbl"): string[] {
  return balancedWordRanges(xml, tag).map(([start, end]) => xml.slice(start, end));
}

function replaceBalancedWordElements(
  xml: string,
  tag: "w:p" | "w:tr" | "w:tbl",
  replacer: (element: string) => string,
): string {
  const ranges = balancedWordRanges(xml, tag);
  if (!ranges.length) return xml;
  let out = "";
  let cursor = 0;
  for (const [start, end] of ranges) {
    out += xml.slice(cursor, start) + replacer(xml.slice(start, end));
    cursor = end;
  }
  return out + xml.slice(cursor);
}

function balancedWordParagraphs(xml: string): string[] {
  return balancedWordElements(xml, "w:p");
}

function decodeXmlText(value: string): string {
  return value
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'");
}

function textBoxWords(xml: string): string {
  return [...xml.matchAll(/<w:t\b[^>]*>([\s\S]*?)<\/w:t>/g)]
    .map((match) => decodeXmlText(match[1]))
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();
}

/** Pull floating text boxes out of the body mammoth reads, and leave a token for each one. */
export function extractWordTextBoxes(xml: string): { xml: string; boxes: string[] } {
  const boxes: string[] = [];
  let next = xml.replace(/<w:txbxContent\b[^>]*>([\s\S]*?)<\/w:txbxContent>/g, (_all, inner: string) => {
    boxes.push(textBoxWords(inner));
    return "<w:txbxContent/>";
  });
  if (!boxes.length && /<wps:wsp\b/.test(xml)) {
    const shapes = [...xml.matchAll(/<wps:wsp\b[\s\S]*?<\/wps:wsp>/g)];
    for (const shape of shapes) {
      const text = [...shape[0].matchAll(/<a:t\b[^>]*>([\s\S]*?)<\/a:t>/g)]
        .map((match) => decodeXmlText(match[1]))
        .join(" ")
        .replace(/\s+/g, " ")
        .trim();
      boxes.push(text);
    }
    if (!boxes.length) boxes.push("");
  }
  if (!boxes.length) return { xml, boxes };
  const tokens = boxes
    .map((_, index) => `<w:p><w:r><w:t>SLTBXTOKEN${index}END</w:t></w:r></w:p>`)
    .join("");
  next = next.includes("</w:body>") ? next.replace("</w:body>", `${tokens}</w:body>`) : `${next}${tokens}`;
  return { xml: next, boxes };
}

/** Swap each text-box token for a text box node. */
export function spliceTextBoxTokens(node: JsonNode, boxes: string[]): JsonNode {
  const visit = (current: JsonNode): JsonNode[] => {
    const joined = (current.content ?? []).map((child) => child.text ?? "").join("");
    const only = /^SLTBXTOKEN(\d+)END$/.exec(joined.trim());
    if ((current.type === "paragraph" || current.type === "heading") && only) {
      return [{ type: "textBox", attrs: { text: boxes[Number(only[1])] ?? "" } }];
    }
    if (current.type === "text" && current.text?.includes("SLTBXTOKEN")) {
      const parts: JsonNode[] = [];
      let last = 0;
      for (const match of current.text.matchAll(/SLTBXTOKEN(\d+)END/g)) {
        const at = match.index ?? 0;
        if (at > last) parts.push({ ...current, text: current.text.slice(last, at) });
        parts.push({ type: "textBox", attrs: { text: boxes[Number(match[1])] ?? "" } });
        last = at + match[0].length;
      }
      if (last < current.text.length) parts.push({ ...current, text: current.text.slice(last) });
      return parts;
    }
    if (!current.content) return [current];
    return [{ ...current, content: current.content.flatMap(visit) }];
  };
  return visit(node)[0] ?? node;
}

async function preprocessDocx(
  zip: JSZip,
  xml: string,
): Promise<{
  extraStyleMap: string[];
  modified: boolean;
  updatedXml: string;
  isCoverPage: boolean;
}> {
  let docXml = xml;
  let stylesXml = zip.file("word/styles.xml")
    ? await zip.file("word/styles.xml")!.async("string")
    : "";
  let numXml = zip.file("word/numbering.xml")
    ? await zip.file("word/numbering.xml")!.async("string")
    : "";

  let modified = false;
  const styles = parseWordStyles(stylesXml);
  const { nums, abstractNums, pStyleToNum } = parseWordNumbering(numXml);
  const counters: Record<string, number[]> = {};
  const extraStyleMap: string[] = [];
  const modifiedStyles = new Set<string>();

  // 1. Process tables: enhance headers and bold formatting
  const isCoverPage =
    /<w:docPartGallery\b[^>]*w:val="Cover Pages"/.test(docXml) ||
    Boolean(
      /<w:alias\b[^>]*w:val="Title"/.test(docXml) &&
      (/<w:alias\b[^>]*w:val="Subtitle"/.test(docXml) ||
        /<w:alias\b[^>]*w:val="Author"/.test(docXml)),
    );
  if (isCoverPage) {
    if (stylesXml && !/<w:style\b[^>]*w:styleId="Heading2"/.test(stylesXml)) {
      stylesXml = stylesXml.replace(
        "</w:styles>",
        '<w:style w:type="paragraph" w:styleId="Heading2"><w:name w:val="heading 2"/></w:style></w:styles>',
      );
      zip.file("word/styles.xml", stylesXml);
    }
    if (stylesXml && !/<w:style\b[^>]*w:styleId="Title"/.test(stylesXml)) {
      stylesXml = stylesXml.replace(
        "</w:styles>",
        '<w:style w:type="paragraph" w:styleId="Title"><w:name w:val="Title"/></w:style></w:styles>',
      );
      zip.file("word/styles.xml", stylesXml);
    }
    if (stylesXml && !/<w:style\b[^>]*w:styleId="Subtitle"/.test(stylesXml)) {
      stylesXml = stylesXml.replace(
        "</w:styles>",
        '<w:style w:type="paragraph" w:styleId="Subtitle"><w:name w:val="Subtitle"/></w:style></w:styles>',
      );
      zip.file("word/styles.xml", stylesXml);
    }
    if (stylesXml && !/<w:style\b[^>]*w:styleId="Centered"/.test(stylesXml)) {
      stylesXml = stylesXml.replace(
        "</w:styles>",
        '<w:style w:type="paragraph" w:styleId="Centered"><w:name w:val="Centered"/></w:style></w:styles>',
      );
      zip.file("word/styles.xml", stylesXml);
    }
    if (stylesXml && !/<w:style\b[^>]*w:styleId="Divider"/.test(stylesXml)) {
      stylesXml = stylesXml.replace(
        "</w:styles>",
        '<w:style w:type="paragraph" w:styleId="Divider"><w:name w:val="Divider"/></w:style></w:styles>',
      );
      zip.file("word/styles.xml", stylesXml);
    }

    extraStyleMap.push(
      "p[style-name='Title'] => h1.center:fresh",
      "p[style-name='Subtitle'] => h2.center:fresh",
      "p[style-name='Centered'] => p.center:fresh",
    );

    docXml = replaceBalancedWordElements(docXml, "w:tbl", (tblXml) => {
      const texts = [...tblXml.matchAll(/<w:t\b[^>]*>([\s\S]*?)<\/w:t>/g)].map(
        (m) => m[1],
      );
      if (texts.length === 0 && !/<a:blip\b|<v:imagedata\b/.test(tblXml)) {
        modified = true;
        return "";
      }

      const rows: string[] = [];
      for (const tr of balancedWordElements(tblXml, "w:tr")) {
        const rowTexts = [...tr.matchAll(/<w:t\b[^>]*>([\s\S]*?)<\/w:t>/g)].map(
          (m) => m[1],
        );
        if (rowTexts.length === 0 && !/<a:blip\b|<v:imagedata\b/.test(tr)) continue;

        const isTitle =
          /w:alias\b[^>]*w:val="Title"/.test(tr) ||
          /w:sz\b[^>]*w:val="80"/.test(tr);
        const isSubtitle =
          /w:alias\b[^>]*w:val="Subtitle"/.test(tr) ||
          /w:sz\b[^>]*w:val="44"/.test(tr);
        const isAuthor = /w:alias\b[^>]*w:val="Author"/.test(tr);
        const isCompany = /w:alias\b[^>]*w:val="Company"/.test(tr);

        const textContent = rowTexts.join("");
        const runProps = coverTextIsBold(tr) ? "<w:rPr><w:b/></w:rPr>" : "";
        if (isTitle) {
          rows.push(
            '<w:p><w:pPr><w:pStyle w:val="Centered"/><w:jc w:val="center"/></w:pPr></w:p>',
            `<w:p><w:pPr><w:pStyle w:val="Title"/><w:jc w:val="center"/></w:pPr><w:r>${runProps}<w:t>${textContent}</w:t></w:r></w:p>`,
          );
        } else if (isSubtitle) {
          rows.push(
            `<w:p><w:pPr><w:pStyle w:val="Subtitle"/><w:jc w:val="center"/></w:pPr><w:r>${runProps}<w:t>${textContent}</w:t></w:r></w:p>`,
          );
        } else if (isAuthor) {
          rows.push(
            '<w:p><w:pPr><w:pStyle w:val="Centered"/><w:jc w:val="center"/></w:pPr></w:p>',
            `<w:p><w:pPr><w:pStyle w:val="Centered"/><w:jc w:val="center"/></w:pPr><w:r><w:rPr><w:b/></w:rPr><w:t>${textContent}</w:t></w:r></w:p>`,
          );
        } else if (isCompany) {
          rows.push(
            `<w:p><w:pPr><w:pStyle w:val="Centered"/><w:jc w:val="center"/></w:pPr><w:r><w:rPr><w:caps/></w:rPr><w:t>${textContent}</w:t></w:r></w:p>`,
          );
        } else {
          const paragraphs = balancedWordParagraphs(tr);
          rows.push(
            ...(paragraphs.length
              ? paragraphs
              : [
                  `<w:p><w:pPr><w:pStyle w:val="Centered"/><w:jc w:val="center"/></w:pPr><w:r><w:t>${textContent}</w:t></w:r></w:p>`,
                ]),
          );
        }
      }
      modified = true;
      return rows.join("");
    });
  } else {
    docXml = docXml.replace(/<w:tbl\b[\s\S]*?<\/w:tbl>/g, (tblXml) => {
      const styleMatch = tblXml.match(/<w:tblStyle\b[^>]*w:val="([^"]+)"/);
      const tblStyleId = styleMatch ? styleMatch[1] : "";
      const tblStyle = tblStyleId ? styles.get(tblStyleId) : undefined;

      const tblLookMatch = tblXml.match(/<w:tblLook\b([^>]*)/);
      const tblLookAttrs = tblLookMatch ? tblLookMatch[1] : "";
      const lookValMatch = tblLookAttrs.match(/w:val="([^"]+)"/);
      const lookVal = lookValMatch ? parseInt(lookValMatch[1], 16) || 0 : 0;

      const isFirstRow =
        /w:firstRow="1"/.test(tblLookAttrs) ||
        Boolean(lookVal & 0x020) ||
        tblLookAttrs === "";
      const isFirstCol =
        /w:firstColumn="1"/.test(tblLookAttrs) || Boolean(lookVal & 0x080);

      let rowIndex = 0;
      return tblXml.replace(
        /<w:tr\b([^>]*)>([\s\S]*?)<\/w:tr>/g,
        (trAll, trAttrs, trBody) => {
          const isHeaderRow =
            /<w:tblHeader\/>/.test(trBody) ||
            (rowIndex === 0 &&
              isFirstRow &&
              Boolean(tblStyle?.tableFirstRowBold)) ||
            /<w:cnfStyle\b[^>]*w:firstRow="1"/.test(trBody);
          let updatedTrBody = trBody;

          if (isHeaderRow) {
            if (/<w:trPr>/.test(updatedTrBody)) {
              if (!/<w:tblHeader\/>/.test(updatedTrBody)) {
                updatedTrBody = updatedTrBody.replace(
                  /<w:trPr>/,
                  "<w:trPr><w:tblHeader/>",
                );
                modified = true;
              }
            } else {
              updatedTrBody = `<w:trPr><w:tblHeader/></w:trPr>` + updatedTrBody;
              modified = true;
            }

            if (tblStyle?.tableFirstRowBold) {
              const bolded = makeBoldRuns(updatedTrBody);
              if (bolded !== updatedTrBody) {
                updatedTrBody = bolded;
                modified = true;
              }
            }
          }

          if (isFirstCol && tblStyle?.tableFirstColBold) {
            let colIndex = 0;
            updatedTrBody = updatedTrBody.replace(
              /<w:tc\b([^>]*)>([\s\S]*?)<\/w:tc>/g,
              (tcAll: string, tcAttrs: string, tcBody: string) => {
                const isTargetCol =
                  colIndex === 0 ||
                  /<w:cnfStyle\b[^>]*w:firstColumn="1"/.test(tcBody);
                colIndex++;
                if (isTargetCol && !isHeaderRow) {
                  const bolded = makeBoldRuns(tcBody);
                  if (bolded !== tcBody) {
                    modified = true;
                    return `<w:tc${tcAttrs}>${bolded}</w:tc>`;
                  }
                }
                return tcAll;
              },
            );
          }

          rowIndex++;
          return `<w:tr${trAttrs}>${updatedTrBody}</w:tr>`;
        },
      );
    });
  }

  // 2. Process paragraphs: headings & numbering
  docXml = docXml.replace(
    /<w:p\b([^>]*)>([\s\S]*?)<\/w:p>/g,
    (pAll, pAttrs, pBody) => {
      const pPrMatch = pBody.match(/<w:pPr>([\s\S]*?)<\/w:pPr>/);
      const pPr = pPrMatch ? pPrMatch[1] : "";

      const pStyleMatch = pPr.match(/<w:pStyle\b[^>]*w:val="([^"]+)"/);
      const styleId = pStyleMatch ? pStyleMatch[1] : undefined;
      const style = styleId ? styles.get(styleId) : undefined;

      const outlineMatch = pPr.match(/<w:outlineLvl\b[^>]*w:val="([^"]+)"/);
      const isHeading = style?.isHeading || Boolean(outlineMatch);
      const headingLevel =
        style?.headingLevel ||
        (outlineMatch ? Math.min(6, parseInt(outlineMatch[1], 10) + 1) : 1);

      if (isHeading && style?.name) {
        extraStyleMap.push(
          `p[style-name='${style.name}'] => h${headingLevel}:fresh`,
        );
      }

      // Check numbering
      const numPrMatch = pPr.match(/<w:numPr>([\s\S]*?)<\/w:numPr>/);
      let numId: string | undefined;
      let ilvl = 0;
      if (numPrMatch) {
        const nid = numPrMatch[1].match(/<w:numId\b[^>]*w:val="([^"]+)"/);
        const lvl = numPrMatch[1].match(/<w:ilvl\b[^>]*w:val="([^"]+)"/);
        if (nid) numId = nid[1];
        if (lvl) ilvl = parseInt(lvl[1], 10) || 0;
      } else if (style?.numPr) {
        numId = style.numPr.numId;
        ilvl = parseInt(style.numPr.ilvl, 10) || 0;
      } else if (styleId && pStyleToNum.has(styleId)) {
        const ref = pStyleToNum.get(styleId)!;
        numId = ref.numId;
        ilvl = ref.ilvl;
      }

      if (isHeading && numId !== undefined) {
        const absId = nums.get(numId);
        const levelMap = absId ? abstractNums.get(absId) : undefined;
        const levelDef = levelMap ? levelMap.get(ilvl) : undefined;

        if (levelDef) {
          const levels = levelMap!;
          if (!counters[numId]) counters[numId] = [];
          if (counters[numId][ilvl] === undefined) {
            counters[numId][ilvl] = levelDef.start;
          } else {
            counters[numId][ilvl]++;
          }
          for (let k = ilvl + 1; k < 9; k++) delete counters[numId][k];

          const numStr = levelDef.lvlText.replace(/%([1-9])/g, (_, d) => {
            const idx = parseInt(d, 10) - 1;
            const cVal = counters[numId][idx] ?? levels.get(idx)?.start ?? 1;
            const fmt = levels.get(idx)?.numFmt || "decimal";
            return formatNumber(cVal, fmt);
          });
          const prefix = numStr + " ";

          if (styleId) modifiedStyles.add(styleId);

          let updatedPBody = pBody.replace(/<w:numPr>[\s\S]*?<\/w:numPr>/, "");
          const textMatch = updatedPBody.match(/<w:t\b[^>]*>([^<]*)/);
          const currentText = textMatch ? textMatch[1] : "";
          if (!currentText.startsWith(numStr)) {
            updatedPBody = updatedPBody.replace(
              /(<w:t\b[^>]*>)/,
              `$1${prefix}`,
            );
          }

          if (style?.isBold) {
            updatedPBody = makeBoldRuns(updatedPBody);
          }

          modified = true;
          return `<w:p${pAttrs}>${updatedPBody}</w:p>`;
        }
      } else if (isHeading && style?.isBold) {
        const bolded = makeBoldRuns(pBody);
        if (bolded !== pBody) {
          modified = true;
          return `<w:p${pAttrs}>${bolded}</w:p>`;
        }
      }

      return pAll;
    },
  );

  // Clean modified heading styles from styles.xml and numbering.xml so Mammoth doesn't listify them
  for (const sId of modifiedStyles) {
    if (stylesXml) {
      stylesXml = stylesXml.replace(
        new RegExp(
          '<w:style\\b[^>]*w:styleId="' + sId + '"[\\s\\S]*?<\\/w:style>',
        ),
        (m) => m.replace(/<w:numPr>[\s\S]*?<\/w:numPr>/, ""),
      );
      zip.file("word/styles.xml", stylesXml);
    }
    if (numXml) {
      numXml = numXml.replace(
        new RegExp('<w:pStyle\\b[^>]*w:val="' + sId + '"[^>]*\\/>'),
        "",
      );
      zip.file("word/numbering.xml", numXml);
    }
  }

  if (modified) {
    zip.file("word/document.xml", docXml);
  }

  return {
    extraStyleMap: [...new Set(extraStyleMap)],
    modified,
    updatedXml: docXml,
    isCoverPage,
  };
}

/** VML pictures Mammoth does not already import as a drawing. */
async function vmlPictureSources(zip: JSZip, xml: string): Promise<string[]> {
  const rels = await zip.file("word/_rels/document.xml.rels")?.async("string");
  if (!rels) return [];
  const targets = new Map<string, string>();
  for (const tag of rels.matchAll(/<Relationship\b[^>]*>/g)) {
    const id = /Id="([^"]+)"/.exec(tag[0])?.[1];
    const target = /Target="([^"]+)"/.exec(tag[0])?.[1];
    if (id && target) targets.set(id, decodeURIComponent(target));
  }
  const out: string[] = [];
  const seen = new Set<string>();
  const add = async (target: string | undefined) => {
    if (!target || seen.has(target)) return;
    const kind = /\.(png|jpe?g|gif|webp)$/i.exec(target)?.[1]?.toLowerCase();
    if (!kind) return;
    const path = target.replace(/^\//, "").replace(/^\.\//, "");
    const part = zip.file(path.startsWith("word/") ? path : `word/${path}`);
    if (!part) return;
    const mime = kind === "jpg" ? "jpeg" : kind;
    out.push(`data:image/${mime};base64,${await part.async("base64")}`);
    seen.add(target);
  };
  const drawing = new Set(
    [...xml.matchAll(/<a:blip\b[^>]*\br:embed="([^"]+)"/g)].map(
      (match) => targets.get(match[1]) ?? "",
    ),
  );
  for (const match of xml.matchAll(/<v:imagedata\b[^>]*\br:id="([^"]+)"/g)) {
    const target = targets.get(match[1]);
    if (target && drawing.has(target)) continue;
    await add(target);
  }
  return out;
}

/**
 * Mammoth refuses a text run that contains another paragraph and then
 * abandons the whole file. Close the run before that paragraph.
 */
function liftBlocksOutOfWordText(xml: string): string {
  if (!/<w:t\b/.test(xml)) return xml;
  const blocks = new Set(["w:p", "w:tbl", "w:sdt"]);
  const stop = new Set(["w:body", "w:tc", "w:hdr", "w:ftr", "w:footnote", "w:endnote"]);
  const surplus = new Map<string, number>();
  const stack: string[] = [];
  let out = "";
  let i = 0;
  while (i < xml.length) {
    if (xml.startsWith("<!--", i) || xml.startsWith("<![CDATA[", i) || xml.startsWith("<?", i)) {
      const closer = xml.startsWith("<!--", i) ? "-->" : xml.startsWith("<?", i) ? "?>" : "]]>";
      const end = xml.indexOf(closer, i + 2);
      const next = end < 0 ? xml.length : end + closer.length;
      out += xml.slice(i, next);
      i = next;
      continue;
    }
    if (xml[i] !== "<") {
      const start = i;
      while (i < xml.length && xml[i] !== "<") i++;
      out += xml.slice(start, i);
      continue;
    }
    const end = xml.indexOf(">", i + 1);
    if (end < 0) {
      out += xml.slice(i);
      break;
    }
    const raw = xml.slice(i, end + 1);
    const closing = raw.startsWith("</");
    const self = /\/\s*>$/.test(raw);
    const name = /^<\/?\s*([A-Za-z0-9:]+)/.exec(raw)?.[1] ?? "";
    if (!closing && !self && blocks.has(name) && stack.includes("w:t")) {
      while (stack.length) {
        const open = stack[stack.length - 1]!;
        if (stop.has(open)) break;
        stack.pop();
        out += `</${open}>`;
        surplus.set(open, (surplus.get(open) ?? 0) + 1);
        if (open === "w:p" || open === "w:tbl" || open === "w:sdt") break;
      }
    }
    if (closing) {
      const found = name ? stack.lastIndexOf(name) : -1;
      if (found >= 0) {
        stack.splice(found);
        out += raw;
      } else if ((surplus.get(name) ?? 0) > 0) {
        surplus.set(name, (surplus.get(name) ?? 0) - 1);
      } else out += raw;
    } else {
      out += raw;
      if (!self && name) stack.push(name);
    }
    i = end + 1;
  }
  return out;
}

/** Mammoth ignores ruby, including the word and its reading. */
function unwrapWordRuby(xml: string): string {
  if (!xml.includes("<w:ruby")) return xml;
  let next = xml.replace(/<w:rubyPr\b[^>]*\/>/g, "");
  let previous = "";
  while (next !== previous) {
    previous = next;
    next = next.replace(/<w:rubyPr\b[^>]*>[\s\S]*?<\/w:rubyPr>/g, "");
  }
  return next.replace(/<\/?w:(?:ruby|rubyBase|rt)\b[^>]*>/g, "");
}

/** Mammoth ignores a content control, including the text inside it. */
function unwrapWordContentControls(xml: string): string {
  if (!xml.includes("<w:sdt")) return xml;
  let next = xml.replace(/<w:sdtPr\b[^>]*\/>/g, "");
  let previous = "";
  while (next !== previous) {
    previous = next;
    next = next.replace(/<w:sdtPr\b[^>]*>[\s\S]*?<\/w:sdtPr>/g, "");
  }
  return next.replace(/<\/?w:sdt(?:Content)?\b[^>]*>/g, "");
}

/**
 * A hidden paragraph mark only hides the line break. Join those paragraphs
 * and leave the words visible.
 */
function joinHiddenParagraphMarks(xml: string): string {
  if (!/<w:pPr\b[\s\S]*?<w:vanish\b/.test(xml)) return xml;
  const matches = [...xml.matchAll(/<w:p\b(?:[^>]*?[^/])>[\s\S]*?<\/w:p>/g)];
  if (!matches.length) return xml;
  const markHidden = (paragraph: string) => {
    const props = /<w:pPr\b[^>]*>[\s\S]*?<\/w:pPr>/.exec(paragraph)?.[0] ?? "";
    const hidden = /<w:vanish\b([^>]*)(?:\/>|>)/.exec(props);
    if (!hidden) return false;
    const val = /w:val="([^"]*)"/.exec(hidden[1])?.[1];
    return val !== "0" && val !== "false" && val !== "off";
  };
  const reveal = (paragraph: string) =>
    paragraph.replace(/<w:pPr\b[^>]*>[\s\S]*?<\/w:pPr>/g, (props) =>
      props
        .replace(/<w:vanish\b[^>]*\/>/g, "")
        .replace(/<w:vanish\b[^>]*>[\s\S]*?<\/w:vanish>/g, ""),
    );
  let out = "";
  let cursor = 0;
  for (let i = 0; i < matches.length; i++) {
    const first = matches[i];
    if (first.index === undefined) continue;
    out += xml.slice(cursor, first.index);
    const parts = [first[0]];
    let end = first.index + first[0].length;
    while (markHidden(parts[parts.length - 1] ?? "") && i + 1 < matches.length) {
      const next = matches[i + 1];
      if (next?.index === undefined || next.index < end) break;
      // A table or another element between the paragraphs stays where it is.
      if (xml.slice(end, next.index).trim()) break;
      i += 1;
      parts.push(next[0]);
      end = next.index + next[0].length;
    }
    const joined =
      parts.length === 1
        ? parts[0]
        : (() => {
            const last = parts[parts.length - 1] ?? "<w:p></w:p>";
            const open = /^<w:p\b[^>]*>/.exec(last)?.[0] ?? "<w:p>";
            const props = /<w:pPr\b[^>]*>[\s\S]*?<\/w:pPr>/.exec(last)?.[0] ?? "";
            const bodies = parts.map((part) =>
              part
                .replace(/^<w:p\b[^>]*>/, "")
                .replace(/<\/w:p>$/, "")
                .replace(/<w:pPr\b[^>]*>[\s\S]*?<\/w:pPr>/, ""),
            );
            return `${open}${props}${bodies.join("")}</w:p>`;
          })();
    out += reveal(joined);
    cursor = end;
  }
  return out + xml.slice(cursor);
}

/** A relationship target with `..` points outside `word/`, which the converter does not read. */
function resolveZipPath(sourcePart: string, target: string): string {
  const parts = sourcePart.split("/").slice(0, -1);
  for (const piece of decodeURIComponent(target).split("/")) {
    if (!piece || piece === ".") continue;
    if (piece === "..") parts.pop();
    else parts.push(piece);
  }
  return parts.join("/");
}

async function relocateEscapingPictures(zip: JSZip): Promise<boolean> {
  let changed = false;
  for (const relName of Object.keys(zip.files)) {
    if (!/^word\/_rels\/.+\.rels$/i.test(relName)) continue;
    const sourcePart = relName.replace("/_rels/", "/").replace(/\.rels$/i, "");
    const file = zip.file(relName);
    if (!file) continue;
    let rels = await file.async("string");
    let relsChanged = false;
    for (const tag of [...rels.matchAll(/<Relationship\b[^>]*>/g)]) {
      const target = /Target="([^"]+)"/.exec(tag[0])?.[1];
      if (!target || !target.includes("..") || !/\.(png|jpe?g|gif|webp)$/i.test(target))
        continue;
      const resolved = resolveZipPath(sourcePart, target);
      const part = zip.file(resolved);
      if (!part) continue;
      const base = resolved.split("/").pop() || "image";
      let dest = `word/media/${base}`;
      if (zip.file(dest) && dest !== resolved) {
        const dot = base.lastIndexOf(".");
        const stem = dot >= 0 ? base.slice(0, dot) : base;
        const ext = dot >= 0 ? base.slice(dot) : "";
        let n = 2;
        while (zip.file(`word/media/${stem}-${n}${ext}`)) n += 1;
        dest = `word/media/${stem}-${n}${ext}`;
      }
      if (!zip.file(dest)) zip.file(dest, await part.async("uint8array"));
      const nextTarget = dest.slice("word/".length);
      if (nextTarget === target) continue;
      rels = rels.replace(tag[0], tag[0].replace(/Target="[^"]+"/, `Target="${nextTarget}"`));
      relsChanged = true;
    }
    if (!relsChanged) continue;
    zip.file(relName, rels);
    changed = true;
  }
  return changed;
}

/** A vanished run is hidden text, not body text. */
function withoutHiddenRuns(xml: string): string {
  if (!/<w:vanish\b/.test(xml)) return xml;
  return xml.replace(/<w:r\b[^>]*>[\s\S]*?<\/w:r>/g, (run) => {
    const hidden = /<w:vanish\b([^>]*)(?:\/>|>[\s\S]*?<\/w:vanish>)/.exec(run);
    if (!hidden) return run;
    const val = /w:val="([^"]*)"/.exec(hidden[1])?.[1];
    if (val === "0" || val === "false" || val === "off") return run;
    return "";
  });
}

/** Mammoth ignores `w:u` unless `w:val` is set. Omitted means single underline. */
function withDefaultUnderline(xml: string): string {
  return xml.replace(/<w:u\b([^>]*)>/g, (full, attrs: string) => {
    if (/\bw:val\s*=/.test(attrs)) return full;
    const selfClosing = attrs.endsWith("/");
    const body = selfClosing ? attrs.slice(0, -1) : attrs;
    return `<w:u w:val="single"${body}${selfClosing ? "/>" : ">"}`;
  });
}

