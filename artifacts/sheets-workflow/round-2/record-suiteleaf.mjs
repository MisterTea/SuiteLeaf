import { chromium } from '@playwright/test';
import { readFile, writeFile, rename } from 'node:fs/promises';
const dir = new URL('./', import.meta.url).pathname;
const file = JSON.parse(await readFile(`${dir}../round-1/baseline.suiteleaf`, 'utf8'));
file.id = crypto.randomUUID(); file.title = 'Sheets parity round 2';
file.content.workbook.id = file.id;
const id=file.content.workbook.sheetOrder[0], sheet=file.content.workbook.sheets[id];
sheet.cellData[2][2].v=425; sheet.cellData[2][3].v=75; sheet.cellData[5][2].v=2030; sheet.cellData[5][3].v=170;
file.content.charts=[]; file.content.workbook.resources=file.content.workbook.resources.filter(r=>!['SHEET_FILTER_PLUGIN','SHEET_DRAWING_PLUGIN','SHEET_DEFINED_NAME_PLUGIN'].includes(r.name));
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:1728,height:960},recordVideo:{dir,size:{width:1728,height:960}}});
const page=await context.newPage(); const pause=()=>page.waitForTimeout(1500);
await page.goto('http://127.0.0.1:5173/');
await page.locator('input[type=file]').setInputFiles({name:'round-2-start.suiteleaf',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(file))});
await page.getByRole('button',{name:'Insert chart',exact:true}).waitFor(); await pause();
const box=page.locator('.sheet-host input.univer-size-full');
await box.fill('A1:C5'); await box.press('Enter'); await pause();
await page.getByRole('button',{name:'Insert chart',exact:true}).click(); await pause();
await page.getByRole('button',{name:'Create chart',exact:true}).click();
const chart=page.getByLabel('Chart: Budget and Actual'); await chart.waitFor(); await pause();
await page.screenshot({path:`${dir}suiteleaf-initial.png`});
const before=await chart.locator('.recharts-bar-rectangle').evaluateAll(es=>es.map(e=>e.getBoundingClientRect().height));
await box.fill('C3'); await box.press('Enter'); await page.keyboard.type('450'); await page.keyboard.press('Enter'); await pause();
const after=await chart.locator('.recharts-bar-rectangle').evaluateAll(es=>es.map(e=>e.getBoundingClientRect().height));
await box.fill('A1:D5'); await box.press('Enter'); await page.getByRole('button',{name:'Create a filter',exact:true}).click(); await pause();
await page.getByRole('button',{name:'Back to files'}).click(); await pause();
await page.getByRole('link',{name:'Sheets parity round 2',exact:true}).click(); await chart.waitFor(); await pause();
await page.screenshot({path:`${dir}suiteleaf-reopened.png`});
const download=page.waitForEvent('download'); await page.getByRole('button',{name:'Download',exact:true}).click(); await (await download).saveAs(`${dir}clean-final.suiteleaf`); await pause();
await writeFile(`${dir}bar-heights.json`,JSON.stringify({before,after},null,2));
const video=page.video(); await context.close(); await rename(await video.path(),`${dir}suiteleaf-clean.webm`); await browser.close();
